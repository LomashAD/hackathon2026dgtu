def stem(tok: str) -> str:
    tok = tok.lower().replace("ё", "е")
    if tok.isdigit():
        return tok
    if len(tok) > 5:
        return tok[:5]
    stripped = re.sub(r"[аеиоуыэюяйь]+$", "", tok)
    return stripped if len(stripped) >= 3 else tok


def tokens(text: str, drop_stop: bool = True) -> list[str]:
    out = []
    for t in TOKEN_RE.findall(text.lower()):
        if drop_stop and (t in STOP or len(t) < 2):
            continue
        out.append(stem(t))
    return out
